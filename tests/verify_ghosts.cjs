const {chromium} = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce',acceptDownloads:true});
  const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>requests.push(r.url()));
  await page.goto(fs.readFileSync('/tmp/mdc-ghost-check/launch-url','utf8'));
  await page.getByRole('heading',{name:'Experimental',exact:true}).waitFor();
  assert.equal(await page.locator('[data-view="ghosts"]').count(),0);
  assert(!requests.some(u=>u.includes('/ghosts')),'Off must not fetch ghost assets or probe endpoints');
  await page.screenshot({path:'/tmp/mdc-ghost-check/settings-off.png'});
  await page.getByRole('switch',{name:'Ghost Files',exact:true}).click();
  await page.getByRole('button',{name:'Open Ghost Files',exact:true}).click();
  await page.locator('.ghost-heading').waitFor();
  await page.locator('.ghost-heading [data-action="ghost-scan"]').click();
  await page.locator('.ghost-card').nth(2).waitFor();
  await page.waitForFunction(()=>!S.busy);
  assert(!requests.some(u=>u.includes('/setup/status')),'Level 1 must not probe AI');
  const cache=page.locator('.ghost-card').filter({hasText:'lantern'});
  const locked=page.locator('.ghost-card').filter({hasText:'Forgotten Notes'});
  assert.equal(await locked.getByRole('button',{name:'Banish to Trash'}).count(),0);
  await locked.getByRole('button',{name:'Review locked ghost',exact:true}).click();
  assert(await page.locator('#confirmDialog [data-action="confirm"]').isDisabled());
  await page.locator('#confirmPhrase').fill('UNLOCK');
  await page.locator('#confirmDialog [data-action="confirm"]').click();
  await locked.getByRole('button',{name:'Banish to Trash',exact:true}).waitFor();
  await page.locator('#main').evaluate(e=>e.scrollTop=0);
  await page.screenshot({path:'/tmp/mdc-ghost-check/ghosts-desktop.png'});
  await cache.getByRole('button',{name:'Banish to Trash',exact:true}).click();
  await page.locator('#confirmDialog').getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await cache.count(),1,'Cancel must preserve the file');
  await cache.getByRole('button',{name:'Banish to Trash',exact:true}).click();
  await page.locator('#confirmDialog [data-action="confirm"]').click();
  await page.locator('.ofrenda li').waitFor();
  assert.equal(await page.locator('.ghost-card').count(),2);
  const prefs=page.locator('.ghost-card').filter({hasText:'atlas'});
  await prefs.getByRole('button',{name:'Let it rest',exact:true}).click();
  await page.getByRole('button',{name:'Show 1 resting ghost',exact:true}).waitFor();
  await page.getByRole('button',{name:'Show 1 resting ghost',exact:true}).click();
  await prefs.waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export ofrenda.md',exact:true}).click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'ofrenda.md');
  await download.saveAs('/tmp/mdc-ghost-check/ofrenda.md');
  assert(fs.readFileSync('/tmp/mdc-ghost-check/ofrenda.md','utf8').includes('lantern'));
  await page.getByRole('button',{name:'Set up AI narration',exact:true}).click();
  await page.locator('#ghostInstall').waitFor();
  assert.equal(await page.locator('#ghostInstall:checked').count(),0);
  await page.getByRole('button',{name:'Run approved steps',exact:true}).click();
  await page.getByText('Consent to each required install, start, and model download step before continuing.',{exact:true}).waitFor();
  await page.locator('#ghostModel').selectOption('llama3.2:1b');
  await page.locator('#ghostInstall').check();
  await page.locator('#ghostStart').check();
  await page.locator('#ghostPull').check();
  await page.screenshot({path:'/tmp/mdc-ghost-check/setup-consent.png'});
  await page.getByRole('button',{name:'Run approved steps',exact:true}).click();
  await page.getByText('Self-test passed. Your local storyteller is ready.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Close AI setup',exact:true}).click();
  await page.getByRole('button',{name:'Narrate the rest',exact:true}).click();
  await page.locator('.ghost-haunting.narrated').first().waitFor();
  await page.waitForFunction(()=>!S.busy);
  assert((await prefs.locator('.ghost-verdict').innerText()).includes('Review first'),'AI cannot promote preferences');
  await page.screenshot({path:'/tmp/mdc-ghost-check/ghosts-ai.png'});
  for(const [width,height] of [[1440,900],[1024,768],[768,1024],[390,844],[320,740],[740,320]]){
    await page.setViewportSize({width,height});
    const overflow=await page.locator('#main').evaluate(main=>{
      const box=main.getBoundingClientRect();
      return [...main.querySelectorAll('*')].filter(e=>{const r=e.getBoundingClientRect();return r.width&&(r.right>box.right+1||r.left<box.left-1)}).map(e=>`${e.tagName}.${e.className}`).slice(0,8);
    });
    assert.deepEqual(overflow,[],`Ghosts overflow ${width}x${height}`);
    await page.locator('#main').evaluate(e=>e.scrollTop=0);
    await page.locator('.toast button').evaluateAll(buttons=>buttons.forEach(b=>b.click()));
    if(width===390)await page.screenshot({path:'/tmp/mdc-ghost-check/ghosts-mobile.png',fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('.ghost-heading [data-view="settings"]').click();
  await page.getByRole('button',{name:'Remove AI components',exact:true}).click();
  await page.locator('#ghostRemove0').check();
  await page.locator('#ghostUninstall').check();
  await page.locator('#confirmDialog [data-action="confirm"]').click();
  await page.waitForFunction(()=>S.features.ghosts_level===1);
  await page.getByRole('switch',{name:'Ghost Files',exact:true}).click();
  await page.waitForFunction(()=>S.features.ghosts_level===0);
  await page.reload();
  await page.getByRole('heading',{name:'Experimental',exact:true}).waitFor();
  assert.equal(await page.locator('[data-view="ghosts"]').count(),0);
  assert.deepEqual(errors,[]);
  console.log('Passed: disabled lazy assets; Level 1 without AI probes; scan/unlock/review/cancel/Trash/ofrenda/hide/export; per-step consent, setup self-test, capped verdict; six responsive sizes; ownership-scoped removal and disable.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
